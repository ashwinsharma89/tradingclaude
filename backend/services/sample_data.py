def get_sample_candles(symbol: str, from_date: str, to_date: str) -> pd.DataFrame:
    """Generate sample OHLCV data for a given symbol and date range."""
    base = _SAMPLE_DATA.get(symbol)
    if base is None:
        return pd.DataFrame()

    start = datetime.strptime(from_date, "%Y-%m-%d")
    end = datetime.strptime(to_date, "%Y-%m-%d")

    rows = []
    current = start
    idx = 0
    while current <= end:
        # Skip weekends
        if current.weekday() < 5:
            data = base[idx % len(base)]
            rows.append({
                "date": current.strftime("%Y-%m-%d"),
                "open": data[0],
                "high": data[1],
                "low": data[2],
                "close": data[3],
                "volume": data[4],
            })
            idx += 1
        current += timedelta(days=1)

    return pd.DataFrame(rows)


